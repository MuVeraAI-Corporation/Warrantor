//! The frozen v1 WAR predicate: a receipt signed before `predicate_version` and `causality`
//! existed must still verify, byte for byte, through the canonical round trip.
//!
//! # Why this file is the gate on the whole task
//!
//! Task 10.1 adds two fields to `WarPredicate`, which is a **signed body**. Every archived receipt
//! was signed over the canonical form of the old shape. If the new fields serialize at all when
//! unset -- as an empty string, as `null`, as `{}` -- the canonical bytes change, every past
//! signature stops verifying, and the archive becomes a pile of apparent forgeries. `Option` plus
//! `skip_serializing_if` is what keeps an absent field absent; this file is what proves it stayed
//! that way.
//!
//! # Why the strings are literals
//!
//! The canonical predicate, the Ed25519 public key and the signature over the DSSE PAE are frozen
//! `const` strings, produced once against `main` before this task changed anything and generated by
//! the *Python* implementation (`python/warrantor_evidence`), not by Rust. A fixture Rust generated
//! from Rust would agree with whatever rule Rust now applies. This one cannot.

use warrantor_evidence::{
    canonical_predicate, causal_verdict, dsse_pae, verify_receipt, CausalRefusal, EvidenceError,
    SignatureEnvelope, WarPredicate, WarReceipt, PREDICATE_TYPE,
};

/// A v1 atomic predicate's canonical form: no `predicate_version`, no `causality`.
const CANONICAL_V1_PREDICATE: &str = r#"{"actor":{"principal":"spiffe://yourcorp/agents/bot-1","svid_digest":"sha256:5v1d","workload_id":"spiffe://yourcorp/agents/bot-1"},"authority":{"chain":[{"capabilities":["github.comment","github.create_pr","github.request_review"],"issuer":"spiffe://yourcorp/issuer","not_after":1786003600,"not_before":1786000000,"subject":"spiffe://yourcorp/agents/bot-1","token_digest":"sha256:c0ffee"}],"effective_capabilities":["github.comment","github.create_pr","github.request_review"],"intersection_proof":{"algorithm":"warrantor-intersect-v1","links_digest":"d777c5703f76fb2c3fc941ccd993cf79774d251c1eefeb280b6d311a8bc66c78","result_digest":"a20eff1dd9120ee67c450f252af1aff3935ac92e9896fe19a42d52e061c7bc28"}},"binding":{"enforcement_mode":"mediated","expires_at":1786003600,"issued_at":1786000000,"nonce":"AAAAAAAAAAAAAAAAAAAAAA==","phase":"atomic","receipt_id":"rcpt-v1-frozen"},"decision":{"engine":"warrantor-notary/1.0","evaluated_at":1786000000,"policy_digest":"sha256:po11cy","verdict":"allow"},"operation":{"class":"warrant.report","consequence_tier":"routine","method":"report","parameters_digest":"sha256:para","reversible":true,"target":"wrt_v1frozen"},"outcome":{"outcome_digest":"sha256:0utc0me","status":"success"}}"#;

/// The verifying key of the throwaway signer, hex.
const PUBLIC_KEY_V1: &str = "94d6fddc70d41dcb0d1436b45e0c65db89272130bd12f6268b468cf4cf177026";

/// Ed25519 over `dsse_pae(CANONICAL_V1_PREDICATE)`, hex. Produced by Python.
const SIGNATURE_V1: &str = "9dce95c0be36410ee0ad5b05ec560da87e7270a6e32b6eb35effcd8ceb5d336dad9cfd60ed307ec05c6d91399c58a46f3214ba9f98c6d53f11dd5a199a438f04";

fn frozen_v1_receipt() -> WarReceipt {
    let predicate: WarPredicate = serde_json::from_str(CANONICAL_V1_PREDICATE)
        .expect("the frozen v1 predicate must still deserialize into the current struct");
    WarReceipt {
        predicate,
        signature: frozen_signature(),
    }
}

fn frozen_signature() -> SignatureEnvelope {
    SignatureEnvelope {
        algorithm: "Ed25519".to_string(),
        key_id: "frozen-v1".to_string(),
        public_key: PUBLIC_KEY_V1.to_string(),
        value: SIGNATURE_V1.to_string(),
    }
}

/// The round trip: v1 JSON in, current struct, canonical form out, and the bytes must be identical.
/// This is the assertion that fails the instant a new field serializes when it is unset.
#[test]
fn a_v1_predicate_round_trips_to_the_same_canonical_bytes() {
    let receipt = frozen_v1_receipt();
    assert_eq!(
        canonical_predicate(&receipt.predicate),
        CANONICAL_V1_PREDICATE,
        "the canonical form of a v1 predicate moved. Every receipt signed before this task is now \
         unverifiable, and a reader would be told the receipt is forged when the truth is that the \
         format changed."
    );
}

/// The signature was taken over those bytes by a key that no longer exists. It must still verify.
#[test]
fn a_signature_taken_before_this_task_still_verifies() {
    verify_receipt(&frozen_v1_receipt())
        .expect("an Ed25519 signature over the frozen v1 canonical bytes must still verify");
}

/// Paired control: change one field of the frozen predicate and the same signature must fail, so
/// the test above is not passing because the verifier accepts everything.
#[test]
fn the_same_signature_over_a_changed_v1_predicate_is_refused() {
    let mut receipt = frozen_v1_receipt();
    receipt.predicate.actor.principal = "spiffe://yourcorp/agents/bot-2".to_string();
    assert!(
        matches!(
            verify_receipt(&receipt),
            Err(EvidenceError::InvalidSignature)
        ),
        "a changed v1 predicate must fail against the frozen signature"
    );
}

/// A v1 predicate has no `causality` section, so the causal verdict over it is a **named refusal**
/// -- not a pass, and not an internal error. A pass here would be the worst outcome this task could
/// ship: a verdict reporting a clean pathway over a record that contains no pathway at all.
#[test]
fn the_causal_verdict_over_a_v1_predicate_is_a_named_refusal_not_a_pass() {
    let receipt = frozen_v1_receipt();
    match causal_verdict(&receipt.predicate) {
        Err(CausalRefusal::Unrepresentable { predicate_version }) => {
            assert_eq!(
                predicate_version, "absent",
                "a v1 predicate carries no version field, and the refusal must say so rather than \
                 inventing one"
            );
            let rendered = CausalRefusal::Unrepresentable { predicate_version }.to_string();
            assert!(
                rendered.contains("no causality section"),
                "the message must say what is missing, got: {rendered}"
            );
            assert!(
                !rendered.contains("clean") && !rendered.contains("no violation"),
                "the message must not imply the pathway was checked and found clean, got: {rendered}"
            );
        }
        other => panic!(
            "a v1 predicate must yield Unrepresentable; anything else claims a pathway was \
             validated over a record that has none. Got {other:?}"
        ),
    }
}

/// The version field is what a reader uses to pick a rule, so its value is pinned to the constant
/// that was declared and unused before this task.
#[test]
fn the_version_constant_is_the_one_the_crate_declares() {
    assert_eq!(PREDICATE_TYPE, "https://warrantor.dev/ActionReceipt/v2");
}

/// A predicate declaring a version this build has never heard of must be refused **as a version
/// mismatch, before the signature is checked**. Reporting it as `InvalidSignature` would tell a
/// third-party auditor that a genuine future receipt is a forgery.
#[test]
fn a_predicate_declaring_an_unknown_version_is_refused_as_a_version_and_not_as_a_forgery() {
    let mut predicate: WarPredicate =
        serde_json::from_str(CANONICAL_V1_PREDICATE).expect("the frozen v1 predicate parses");
    predicate.predicate_version = Some("https://warrantor.dev/ActionReceipt/v9".to_string());
    let receipt = WarReceipt {
        predicate,
        signature: frozen_signature(),
    };
    match verify_receipt(&receipt) {
        Err(EvidenceError::UnknownVersion(version)) => assert_eq!(
            version, "https://warrantor.dev/ActionReceipt/v9",
            "the refusal must name the version it did not recognize"
        ),
        other => panic!(
            "an unknown predicate_version must be reported as a version mismatch, not as \
             {other:?}. This receipt's signature is also wrong -- deliberately -- so a build that \
             checks the signature first reports a forgery about a format it simply does not know."
        ),
    }
}

/// Paired control: the versions this build *does* recognize -- absent, and `PREDICATE_TYPE` -- both
/// reach the signature check rather than being refused as unknown.
#[test]
fn a_recognized_version_reaches_the_signature_check() {
    let mut predicate: WarPredicate =
        serde_json::from_str(CANONICAL_V1_PREDICATE).expect("the frozen v1 predicate parses");
    predicate.predicate_version = Some(PREDICATE_TYPE.to_string());
    let receipt = WarReceipt {
        predicate,
        signature: frozen_signature(),
    };
    // Adding the version changed the canonical bytes, so the frozen signature no longer matches --
    // and that is exactly the error a reader should see: a real signature mismatch, reported as
    // one, on a version this build knows.
    assert!(
        matches!(
            verify_receipt(&receipt),
            Err(EvidenceError::InvalidSignature)
        ),
        "a recognized version must not short-circuit as UnknownVersion"
    );
}

/// The silent-drop hole on the predicate, the twin of the one on `notary::ReceiptBody`.
#[test]
fn a_predicate_carrying_an_unknown_field_is_refused_at_parse() {
    let with_extra =
        CANONICAL_V1_PREDICATE.replace(r#"{"actor":"#, r#"{"pathway_checked":true,"actor":"#);
    let error = serde_json::from_str::<WarPredicate>(&with_extra)
        .expect_err("an unknown field on a signed body must be refused, never silently dropped");
    assert!(
        error.to_string().contains("pathway_checked"),
        "the refusal must name the field, got: {error}"
    );
}

/// The DSSE prefix is part of the signed bytes, so it is pinned too: a change there would break
/// every signature just as surely as a change to the canonical JSON.
#[test]
fn the_dsse_pre_auth_encoding_of_the_frozen_predicate_is_unchanged() {
    let pae = dsse_pae(CANONICAL_V1_PREDICATE);
    let expected = format!("DSSEv1 {} ", CANONICAL_V1_PREDICATE.len());
    assert!(pae.starts_with(expected.as_bytes()), "the PAE header moved");
    assert_eq!(pae.len(), expected.len() + CANONICAL_V1_PREDICATE.len());
}
