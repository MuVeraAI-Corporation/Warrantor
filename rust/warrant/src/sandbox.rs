    #[test]
    fn the_worktree_bind_comes_after_the_read_only_root() {
        // bwrap applies binds in order and later ones win. A worktree bound BEFORE `--ro-bind / /`
        // is shadowed read-only, and the agent cannot write its own worktree -- a profile that
        // looks right, runs, and breaks everything.
        let profile = profile(
            &bounds(&["src/**"], &[]),
            "/home/u/wt",
            Confinement::Bubblewrap,
        );
        let ro_root = profile
            .argv
            .iter()
            .position(|a| a == "--ro-bind")
            .expect("a read-only root");
        let rw_tree = profile
            .argv
            .iter()
            .position(|a| a == "--bind")
            .expect("a read-write worktree");
        assert!(
            rw_tree > ro_root,
            "the worktree bind must come after the root bind or it is shadowed: {:?}",
            profile.argv
        );
    }

