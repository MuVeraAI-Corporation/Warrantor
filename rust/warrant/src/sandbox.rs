//! Turning a warrant's bounds into a confinement profile something else can enforce.
//!
//! # What this is, said before anything else
//!
//! **This module emits a command line. It enforces nothing.** A profile that is never launched
//! confines nothing at all, and a bound does not move from
//! [`BoundStrength::Observed`](crate::BoundStrength::Observed) to
//! [`Enforced`](crate::BoundStrength::Enforced) because a file describing it exists.
//! [`crate::bound_strengths`] is unchanged by this module and must stay unchanged by it.
//!
//! # Why it exists anyway
//!
//! `docs/W1-delivery-gaps.md` §3.1 is the one open item where the product's central sentence is
//! stronger than what the code earns: `write_paths` is **Observed**, there is no netns, no seccomp
//! and no firewall, and the honest advice has always been "compose with a real sandbox". That
//! advice was unactionable. An operator who accepted it had to read the warrant, work out which of
//! its bounds a sandbox could hold, and hand-write a `bwrap` line — and the interesting part of
//! that job is not the typing, it is knowing **which bounds a sandbox cannot express at all**.
//!
//! This makes the advice executable and, more usefully, makes the gaps in it explicit.
//!
//! # The asymmetry that makes this worth a module
//!
//! A confinement profile can be **stricter than the warrant**, and that is its own failure.
//! `bubblewrap --unshare-net` is all-or-nothing: there is no host allowlist in a network
//! namespace. So a warrant permitting `api.github.com` produces a profile that denies *all*
//! network — the agent then fails at its first fetch, the operator concludes Warrantor is broken,
//! and the profile that caused it was generated by Warrantor.
//!
//! [`Divergence`] names both directions. A bound the sandbox cannot hold is a gap; a bound the
//! sandbox holds *harder than the warrant asked* is a break. Neither may be silent, and the second
//! is the one nobody expects.
//!
//! # Verified against a real kernel, and what that found
//!
//! The derivation below is unit-tested. It has also, since 2026-08-17, been **executed**: built for
//! Linux and run under bubblewrap on a 6.18 kernel with unprivileged user namespaces, against a
//! warrant granted with `--write 'src/**'` on a real git worktree.
//!
//! Three of the four claims held on the first run. The fourth did not, and it was mine:
//!
//! | claim | result |
//! |---|---|
//! | a write inside the worktree succeeds and persists to the host | held |
//! | a write to `$HOME` or `/etc` fails at the syscall | held — `EROFS`, "Read-only file system" |
//! | with no egress granted, DNS does not resolve | held — `getent` exits 2 inside, 0 outside |
//! | *"a write outside the worktree FAILS at the syscall"* | **false for `/tmp`** |
//!
//! `--tmpfs /tmp` gives the sandbox a private `/tmp`, so a write there **succeeds**, stays readable
//! for the rest of the session, and is silently discarded at exit. That is a third outcome the
//! sentence did not have a word for: not refused, not persisted. An operator told "fails at the
//! syscall" would wait for an error that never arrives, and an agent using `/tmp` as durable
//! scratch is never told its work evaporated. The `write_paths` sentence now names it.
//!
//! Finding that required running it. Every unit test in this file passed before and after; nothing
//! in a derivation can tell you what a kernel does with it.
//!
//! # It fails closed, and that is the part a wrapper can undo
//!
//! Three setup failures were then driven deliberately: a bind source that does not exist (a
//! worktree deleted between grant and launch), a bind target it cannot create, and a `--chdir` into
//! a path the sandbox does not have. All three exited 1 with a named error, and **the wrapped
//! command never ran**. See [`EXIT_CODE_WARNING`], which is printed with every profile, because the
//! easiest way to lose this property is a wrapper script: `bwrap ... agent || agent` turns a refused
//! sandbox into an unconfined run, and `bwrap ... agent; agent` does it without anyone typing `||`.
//!
//! What remains outside this crate's claim: whether bubblewrap is correct is bubblewrap's claim,
//! not Warrantor's, and one kernel is not every kernel — WSL2's 6.18 is not a hardened distro
//! kernel with `unprivileged_userns_clone` disabled, where `bwrap` will refuse to start at all.
//! That refusal is the same fail-closed direction as the three above, which is why it is a caveat
//! about coverage rather than about safety.

use std::collections::BTreeSet;

use serde::{Deserialize, Serialize};

use crate::WarrantBounds;

/// The confinement tools this module can write a profile for.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Confinement {
    /// `bubblewrap` — unprivileged user namespaces, per-path bind mounts, optional netns.
    ///
    /// The default because it is the only one of the two that expresses a *read-only everything
    /// else* filesystem without a policy language, which is the shape `write_paths` needs.
    Bubblewrap,
    /// `firejail` — profile-driven, more widely packaged, coarser.
    Firejail,
}

impl Confinement {
    /// The word it is written as.
    #[must_use]
    pub const fn word(self) -> &'static str {
        match self {
            Self::Bubblewrap => "bubblewrap",
            Self::Firejail => "firejail",
        }
    }

    /// Parse one.
    ///
    /// # Errors
    /// A sentence naming the two, because a typo silently selecting the wrong confinement is worse
    /// than a refusal.
    pub fn parse(word: &str) -> Result<Self, String> {
        match word.trim() {
            "bubblewrap" | "bwrap" => Ok(Self::Bubblewrap),
            "firejail" => Ok(Self::Firejail),
            other => Err(format!(
                "{other:?} is not a confinement this build writes profiles for. The two are: \
                 bubblewrap, firejail."
            )),
        }
    }

    /// The platform this profile runs on. Both are Linux-only, and saying so is the point.
    #[must_use]
    pub const fn platform(self) -> &'static str {
        "linux"
    }

    /// The argument that makes the root read-only, spelled the way this kind's profile spells it.
    ///
    /// Named per kind because a sentence about the firejail profile shipped citing `--ro-bind / /`,
    /// which is bubblewrap's flag and appears nowhere in a firejail argv. A reader who went looking
    /// for it in the command they were about to paste would not have found it. The profile tests
    /// pin that this string is in the argv of the kind it names.
    #[must_use]
    pub const fn read_only_root_flag(self) -> &'static str {
        match self {
            Self::Bubblewrap => "--ro-bind / /",
            Self::Firejail => "--read-only=/",
        }
    }
}

/// One path a profile mounts read-write, and the argument that opened it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReadWriteHole {
    /// The path inside the sandbox.
    pub path: String,
    /// The argv fragment that opened it, so a reader can find it in the command.
    pub opened_by: String,
}

/// Every read-write hole an argv opens, read off the argv itself.
///
/// # Why this reads the command rather than the kind
///
/// The command is the thing the operator pastes, so a sentence about what it mounts read-write has
/// to be derived from it or the sentence describes a profile that is not the one launched.
/// `scorer::isolation` shipped an `Enforced` tier whose mechanism sentence called the worktree "the
/// only read-write hole" while the same argv carried `--tmpfs /tmp` — a second hole a
/// derivation-only reading missed, and one the test suite's own helper knew about while the
/// production check did not. A reviewer caught it. This function is what both now read.
///
/// The holes recognized: `--bind <src> <dst>` (the destination is the path inside the sandbox),
/// `--tmpfs <path>`, `--read-write=<path>`, `--whitelist=<path>`, and `--private-tmp`, which is a
/// private tmpfs over `/tmp`. A firejail whitelist mounts a host path in; whether it is writable
/// depends on the `--read-only`/`--read-write` arguments beside it, and this reading takes the
/// fail-closed side by counting it. Nothing here launches anything: it is a reading of the argv,
/// and a hole this parser does not know is a hole no sentence built on it will name.
#[must_use]
pub fn read_write_holes_in(argv: &[String]) -> Vec<ReadWriteHole> {
    let mut holes = Vec::new();
    let mut arguments = argv.iter();
    while let Some(argument) = arguments.next() {
        match argument.as_str() {
            "--bind" => {
                let source = arguments.next();
                if let (Some(source), Some(destination)) = (source, arguments.next()) {
                    holes.push(ReadWriteHole {
                        path: destination.clone(),
                        opened_by: format!("--bind {source} {destination}"),
                    });
                }
            }
            "--tmpfs" => {
                if let Some(path) = arguments.next() {
                    holes.push(ReadWriteHole {
                        path: path.clone(),
                        opened_by: format!("--tmpfs {path}"),
                    });
                }
            }
            "--private-tmp" => holes.push(ReadWriteHole {
                path: "/tmp".to_string(),
                opened_by: "--private-tmp".to_string(),
            }),
            other => {
                for prefix in ["--read-write=", "--whitelist="] {
                    if let Some(path) = other.strip_prefix(prefix) {
                        holes.push(ReadWriteHole {
                            path: path.to_string(),
                            opened_by: other.to_string(),
                        });
                    }
                }
            }
        }
    }
    holes
}

/// Compare two paths the way a bind mount does: by prefix, separator-insensitively, and
/// case-insensitively — the last is wrong for a Linux filesystem and is chosen anyway, because the
/// error it makes refuses an `Enforced` tier rather than granting one.
fn covers(hole: &str, path: &str) -> bool {
    let normalize = |p: &str| p.replace('\\', "/").to_lowercase();
    let (hole, path) = (normalize(hole), normalize(path));
    let hole = hole.trim_end_matches('/');
    path == hole || path.starts_with(&format!("{hole}/"))
}

/// A bound and how the emitted profile relates to it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "kebab-case")]
pub enum Divergence {
    /// The profile holds this bound at least as tightly as the warrant states it.
    Held {
        /// The bound's name, as [`crate::bound_strengths`] spells it.
        bound: String,
        /// How, in one sentence.
        how: String,
    },
    /// The profile cannot express this bound at all. It stays exactly as strong as it was.
    Gap {
        /// The bound.
        bound: String,
        /// Why no confinement of this kind can hold it, and what does.
        why: String,
    },
    /// The profile is **stricter** than the warrant. The agent will be refused things the warrant
    /// permits, and the refusal will not look like Warrantor.
    Overreach {
        /// The bound.
        bound: String,
        /// What the warrant permits that this profile denies.
        why: String,
    },
}

impl Divergence {
    /// The bound this is about.
    #[must_use]
    pub fn bound(&self) -> &str {
        match self {
            Self::Held { bound, .. } | Self::Gap { bound, .. } | Self::Overreach { bound, .. } => {
                bound
            }
        }
    }

    /// The word a listing renders.
    #[must_use]
    pub const fn word(&self) -> &'static str {
        match self {
            Self::Held { .. } => "held",
            Self::Gap { .. } => "gap",
            Self::Overreach { .. } => "OVERREACH",
        }
    }
}

/// A confinement profile: the command, and an honest account of what it does and does not do.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Profile {
    /// Which tool.
    pub confinement: Confinement,
    /// The argv prefix. The agent's own command follows it.
    ///
    /// A prefix rather than a whole command line: this module does not know what the operator runs,
    /// and inventing an agent invocation would produce something that looks runnable and is not.
    pub argv: Vec<String>,
    /// Every bound, and how this profile relates to it. Never a subset — a bound missing from this
    /// list would be one nobody was told about.
    pub divergences: Vec<Divergence>,
    /// The sentence this profile carries about its own limits.
    pub caveat: String,
}

/// What a non-zero exit from the confinement means, and the wrapper mistake it invites.
///
/// Verified rather than assumed: three setup failures were driven against bubblewrap on Linux
/// 6.18 — a bind source that does not exist (a worktree deleted between grant and launch), a bind
/// target it cannot create, and a `--chdir` into a path the sandbox does not have. All three exited
/// 1 with a named error, and **the wrapped command never ran** in any of them.
///
/// That is the fail-closed direction and it is the right one. It is also the thing a wrapper script
/// most easily undoes: `bwrap ... agent || agent` and `bwrap ... agent; agent` both turn a refused
/// sandbox into an unconfined run, and the second is what a shell does by default if nobody checks.
pub const EXIT_CODE_WARNING: &str =
    "IF THE CONFINEMENT EXITS NON-ZERO, YOUR AGENT DID NOT RUN. Verified against bubblewrap on Linux 6.18: a missing bind source, an uncreatable bind target and a bad --chdir all exit 1 with a named error and never execute the wrapped command -- which is the correct direction. Do NOT let a wrapper fall back to running the agent unconfined on that exit code; a script that ignores it turns a refused sandbox into an unsupervised run, which is worse than not having attempted one.";

/// The caveat every profile carries.
///
/// In the profile rather than only in this module's docs, because the person who most needs it is
/// the one about to paste the command, and they are not reading rustdoc.
pub const PROFILE_CAVEAT: &str =
    "This is a COMMAND, not an enforcement. Nothing is confined until you launch the agent under \
     it, and Warrantor cannot tell whether you did -- `warrantor report` will still say \
     write_paths is Observed, because from this store's point of view it is. The confinement is \
     bubblewrap's or firejail's claim, not Warrantor's. Read the divergences below before using \
     it: a profile that is STRICTER than the warrant will break the agent in a way that does not \
     look like Warrantor refusing anything.";

/// Whether a path can appear in a Linux confinement command at all.
///
/// # Why this is a refusal and not a warning
///
/// The first live run of `warrantor sandbox` on Windows emitted
/// `bwrap --bind 'M:\wt-depth\.warrantor\wrt_...'` — a syntactically perfect command containing a
/// path that cannot exist on the only platform it runs on. It reads as runnable. Pasted into a
/// Linux shell it fails with bwrap's own error about a missing path, which names the symptom and
/// not the cause, and the operator is left debugging a sandbox rather than a store that was made
/// on another operating system.
///
/// A command that cannot work must not be printed as though it could. That is the same rule the
/// `--upstream` defect established: naming a remedy that does not exist costs more than naming
/// none.
///
/// # Errors
/// A sentence naming the path and what to do about it.
pub fn check_worktree(worktree: &str) -> Result<(), String> {
    // `char::from(92)` is a backslash. Written this way because every attempt to embed the
    // literal through the tooling that generated this file mangled the escape, and a mangled
    // escape here silently stops detecting Windows paths -- the exact defect this guards.
    let has_backslash = worktree.contains(char::from(92));
    if worktree.starts_with('/') && !has_backslash {
        return Ok(());
    }
    Err(format!("{worktree:?} is not an absolute POSIX path, and every confinement this module writes for is Linux-only. A profile naming this path would be a command that LOOKS runnable and cannot be: pasted into a Linux shell it fails with the sandbox's own error about a missing directory, which names the symptom and not the cause. This store was almost certainly created on Windows or macOS -- grant the warrant on the host that will run the agent, or translate the path yourself and pass it deliberately."))
}

/// Write a confinement profile for one warrant's bounds.
///
/// `worktree` is the one path the agent must be able to write. Everything else the profile mounts
/// is read-only, which is the whole reason `write_paths` is expressible at all here.
///
/// # The choice not to translate `write_paths` glob-by-glob
///
/// `write_paths` holds globs relative to the worktree (`src/**`), and a bind mount takes paths. A
/// profile that bound each glob's *directory* read-write would be wrong in the direction that
/// matters: `src/**` would become a read-write `src/`, and an agent writing `src/anything` would be
/// permitted by the sandbox and refused by the warrant. The sandbox would then be *looser* than the
/// bound while appearing to enforce it, which is worse than not enforcing it at all.
///
/// So the worktree is bound read-write as a whole and the glob refinement stays where it already
/// is — with settle, which does not stage out-of-bounds paths. The profile reports this as
/// [`Divergence::Held`] against *containment*, and the sentence says exactly how much it holds.
#[must_use]
pub fn profile(bounds: &WarrantBounds, worktree: &str, confinement: Confinement) -> Profile {
    let mut argv: Vec<String> = Vec::new();
    let mut divergences: Vec<Divergence> = Vec::new();

    match confinement {
        Confinement::Bubblewrap => {
            argv.push("bwrap".to_string());
            // Read-only root, then one read-write hole. Order matters to bwrap: later binds win, so
            // the worktree must come after the root bind or it is shadowed read-only.
            argv.extend(["--ro-bind", "/", "/"].map(String::from));
            argv.extend(["--dev", "/dev"].map(String::from));
            argv.extend(["--proc", "/proc"].map(String::from));
            argv.extend(["--tmpfs", "/tmp"].map(String::from));
            argv.extend(["--bind", worktree, worktree].map(String::from));
            argv.extend(["--chdir", worktree].map(String::from));
            // The agent must not outlive the sandbox, which is the same property the supervisor
            // already holds with a job object and PR_SET_PDEATHSIG.
            argv.push("--die-with-parent".to_string());
            argv.push("--new-session".to_string());
        }
        Confinement::Firejail => {
            argv.push("firejail".to_string());
            argv.push("--quiet".to_string());
            argv.push("--noprofile".to_string());
            argv.push(format!("--whitelist={worktree}"));
            argv.push("--read-only=/".to_string());
            argv.push(format!("--read-write={worktree}"));
            argv.push("--private-tmp".to_string());
            argv.push(format!("--chdir={worktree}"));
        }
    }

    divergences.push(Divergence::Held {
        bound: "write_paths".to_string(),
        how: format!(
            "everything outside {worktree} is mounted read-only, so a write to a real path outside \
             the worktree FAILS at the syscall with EROFS rather than being noticed at settle -- \
             verified against bubblewrap on Linux 6.18, where $HOME and /etc both refuse with \
             \"Read-only file system\". THE EXCEPTION IS /tmp, which this profile replaces with a \
             private tmpfs: a write there SUCCEEDS, stays visible to the agent for the rest of the \
             session, and is discarded when the sandbox exits. That is contained, and it is NOT \
             refused -- an agent treating /tmp as durable scratch is not told otherwise. The glob \
             refinement inside the worktree ({}) is NOT expressed here and stays where it already \
             is: settle does not stage out-of-bounds paths. Binding each glob's directory \
             read-write would make the sandbox LOOSER than the bound while appearing to enforce it.",
            if bounds.write_paths.is_empty() {
                "none granted".to_string()
            } else {
                bounds.write_paths.iter().cloned().collect::<Vec<_>>().join(", ")
            }
        ),
    });

    // ── network ───────────────────────────────────────────────────────────────────────
    //
    // The asymmetry this module exists to surface. A network namespace is all-or-nothing.
    if bounds.egress_hosts.is_empty() {
        match confinement {
            Confinement::Bubblewrap => argv.push("--unshare-net".to_string()),
            Confinement::Firejail => argv.push("--net=none".to_string()),
        }
        divergences.push(Divergence::Held {
            bound: "egress_hosts".to_string(),
            how: "the warrant grants no egress and the profile unshares the network namespace, so \
                  there is no route out even for a process that never touches the MCP proxy. This \
                  is the one case where a sandbox turns egress_hosts from Mediated into something \
                  an agent cannot route around."
                .to_string(),
        });
    } else {
        // Deliberately NOT emitted. A profile that silently denied permitted egress would break the
        // agent, and the operator would blame the wrong thing.
        divergences.push(Divergence::Overreach {
            bound: "egress_hosts".to_string(),
            why: format!(
                "this warrant permits {} host(s) ({}), and a network namespace has no host \
                 allowlist -- it is all or nothing. `--unshare-net` is therefore NOT in the command \
                 above: adding it would deny egress the warrant grants, the agent would fail at its \
                 first fetch, and nothing in that failure would look like a bound refusing \
                 anything. Egress stays Mediated, held by the MCP proxy. To make it enforced, put a \
                 filtering proxy in the namespace and allow only that.",
                bounds.egress_hosts.len(),
                bounds.egress_hosts.iter().cloned().collect::<Vec<_>>().join(", ")
            ),
        });
    }

    // ── the store, which is not a bound and is the thing a grader must not leak ───────
    //
    // Task 13.7. Every divergence above and below is keyed to a `WarrantBounds` field, and that is
    // exactly why this one was missing: nobody grants a warrant the authority to read
    // `~/.warrantor/keys/settle.key`, so no field named it and the surface whose whole job is
    // enumerating what a profile CANNOT hold said nothing about the one credential whose leak
    // converts a scored agent into the party that settles its own score.
    //
    // It is a Gap and not an Observed anything: "observed" implies something measures it, and
    // nothing in this repository looks at this read, let alone refuses it.
    //
    // Both sentences below are DERIVED from the argv built above rather than written beside it.
    // This shipped as one constant for both kinds: it cited `--ro-bind / /` under the firejail
    // profile, whose argv has no such flag, and it said the profile "does stop the agent WRITING
    // the store" unconditionally -- false for a store under the worktree or under /tmp, both of
    // which the same argv mounts read-write. A reviewer caught both. `profile` has no store-root
    // input, so what it can say honestly is which holes it opens and which command decides per
    // store.
    let holes = read_write_holes_in(&argv)
        .into_iter()
        .map(|hole| format!("{} ({})", hole.path, hole.opened_by))
        .collect::<Vec<_>>()
        .join(", ");
    divergences.push(Divergence::Gap {
        bound: "scorer_credentials".to_string(),
        why: format!(
            "read-only is not unreadable. `{}` mounts the whole filesystem, $HOME included, so \
             ~/.warrantor/keys/settle.key -- the key that releases staged effects for real -- stays \
             READABLE to the confined process, and nothing in this repository refuses that read at \
             any tier. Same UID is same UID. The profile stops the agent WRITING the store -- which \
             is what protects the guard and run logs a scorer reads from being edited by the party \
             being scored -- ONLY for a store outside every read-write hole this command opens: \
             {holes}. A store under one of those is writable by the party being scored, and \
             `warrantor scorer <id> --confined` is the command that decides which case a given \
             store is in. Either way the profile does nothing about the agent COPYING the settle \
             key out. What would hold it is a separate user account for the store, or a sandbox \
             invocation that binds ~/.warrantor as a tmpfs rather than inheriting it from the \
             read-only root -- neither of which this module emits, because a profile that hid the \
             store would break `warrantor settle` from inside the sandbox and the breakage would \
             not look like Warrantor refusing anything.",
            confinement.read_only_root_flag()
        ),
    });

    // ── the bounds no filesystem or network confinement can hold ──────────────────────
    divergences.push(Divergence::Gap {
        bound: "tools".to_string(),
        why: "a tool allowlist is a property of the MCP conversation, not of the process. A \
              sandbox cannot tell a permitted tool call from a refused one because both arrive as \
              the same syscalls. Stays Mediated, held by the proxy."
            .to_string(),
    });
    divergences.push(Divergence::Gap {
        bound: "staged_classes".to_string(),
        why: "staging is a decision about what to DO with an effect, taken after the effect is \
              described. No confinement expresses it. Stays Mediated."
            .to_string(),
    });
    divergences.push(Divergence::Gap {
        bound: "budget_cents_observed".to_string(),
        why: "the budget is parsed from the agent's own self-reporting and no sandbox can meter \
              tokens. Stays Observed, and its name says so."
            .to_string(),
    });
    divergences.push(Divergence::Gap {
        bound: "delegation_depth".to_string(),
        why: "held by an Ed25519 signature, which is already stronger than anything a sandbox \
              adds. Stays Enforced."
            .to_string(),
    });
    divergences.push(Divergence::Gap {
        bound: "expires_at".to_string(),
        why: "held by the supervisor's OS process link -- a Windows job object, or setsid plus \
              PR_SET_PDEATHSIG. `--die-with-parent` above reinforces it and does not replace it. \
              Stays Enforced."
            .to_string(),
    });

    Profile {
        confinement,
        argv,
        divergences,
        caveat: PROFILE_CAVEAT.to_string(),
    }
}

impl Profile {
    /// Every bound this profile is stricter about than the warrant.
    #[must_use]
    pub fn overreaches(&self) -> Vec<&Divergence> {
        self.divergences
            .iter()
            .filter(|d| matches!(d, Divergence::Overreach { .. }))
            .collect()
    }

    /// The bounds this profile actually holds.
    #[must_use]
    pub fn held(&self) -> Vec<&Divergence> {
        self.divergences
            .iter()
            .filter(|d| matches!(d, Divergence::Held { .. }))
            .collect()
    }

    /// Every path this profile mounts read-write, read off its own argv. See
    /// [`read_write_holes_in`] for why the argv and not the kind is the source.
    #[must_use]
    pub fn read_write_holes(&self) -> Vec<ReadWriteHole> {
        read_write_holes_in(&self.argv)
    }

    /// The read-write hole covering `path`, if this profile opens one.
    ///
    /// `Some` means a write to `path` inside the sandbox is not refused by the read-only root — it
    /// lands in the hole, which for `--bind` is the host filesystem and for a tmpfs is a private
    /// mount discarded at exit. `None` means the path sits under the read-only root.
    #[must_use]
    pub fn hole_over(&self, path: &str) -> Option<ReadWriteHole> {
        self.read_write_holes()
            .into_iter()
            .find(|hole| covers(&hole.path, path))
    }

    /// Whether this profile unshares the network namespace, read off its own argv.
    ///
    /// `--unshare-net` and `--net=none` are emitted only for a warrant that grants no egress, and a
    /// tier that claims the namespace has to read the argv that would install it rather than
    /// re-deciding `egress_hosts.is_empty()` beside it — the two conditions were the same
    /// expression written twice, and a reviewer showed the second copy could be edited with no
    /// test going red.
    #[must_use]
    pub fn unshares_network(&self) -> bool {
        self.argv
            .iter()
            .any(|argument| argument == "--unshare-net" || argument == "--net=none")
    }

    /// The command as a single shell line.
    ///
    /// Each argument is single-quoted unless it is already safe, because a worktree path can hold a
    /// space and a profile that breaks on one is a profile nobody uses twice.
    #[must_use]
    pub fn shell_line(&self) -> String {
        self.argv
            .iter()
            .map(|a| shell_quote(a))
            .collect::<Vec<_>>()
            .join(" ")
    }
}

/// Quote one argument for a POSIX shell.
///
/// Single quotes, with the standard `'\''` escape for an embedded single quote. Not a general
/// shell-escaping library — it handles exactly the arguments this module produces, which are a
/// fixed set of flags plus one operator-supplied path.
fn shell_quote(argument: &str) -> String {
    let safe = !argument.is_empty()
        && argument
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || "-_./=:".contains(c));
    if safe {
        return argument.to_string();
    }
    format!("'{}'", argument.replace('\'', r"'\''"))
}

/// The set of bound names a profile must speak about.
///
/// Taken from [`crate::bound_strengths`] rather than written out again, so a bound added there
/// without being considered here is a test failure rather than a silent omission from every
/// profile this module writes.
#[must_use]
pub fn bounds_to_cover() -> BTreeSet<&'static str> {
    crate::bound_strengths()
        .into_iter()
        .map(|(name, _)| name)
        .collect()
}

